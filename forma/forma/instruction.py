def _signature(spec: dict) -> str:
    name = spec["name"]
    params = [p["name"] for p in spec.get("params") or []]
    head = f"{name} [объект]" if params and params[0] == "objects" else name
    rest = [p for p in params if p != "objects"]
    tail = " ".join(f"{p}=…" for p in rest[:6])
    if len(rest) > 6:
        tail += " …"
    return f"  имя = {head} {tail}".rstrip()


def commands_catalog() -> str:
    """Все команды приложения в исполнимом виде — для копирования целиком."""
    out = [f"# ФОРМА 3D {__version__} — ПОЛНЫЙ СПИСОК КОМАНД", "",
           "Каждая строка — готовая команда сценария. В скобках — значение по",
           "умолчанию. Пример под командой можно вставить как есть.", ""]
    by_cat: dict[str, list[dict]] = {}
    for spec in commands_help():
        by_cat.setdefault(spec["category"], []).append(spec)
    total = 0
    for cat, specs in by_cat.items():
        out.append(f"## {cat} ({len(specs)})")
        out.append("")
        for spec in specs:
            total += 1
            alias = ", ".join(spec.get("aliases") or [])
            title = f"### {spec['name']}"
            if alias:
                title += f"  (синонимы: {alias})"
            out.append(title)
            summary = (spec.get("summary") or "").strip().replace("\n", " ")
            if summary:
                out.append(summary)
            if spec.get("orientation"):
                out.append("  исходная ориентация: " + spec["orientation"])
            out.append(f"  вызов: {_signature(spec).strip()}")
            params = spec.get("params") or []
            if params:
                out.append("  параметры:")
                for p in params:
                    out.append(f"    · {p['name']} — {p['desc']}")
            example = (spec.get("example") or "").strip()
            if example:
                out.append("  пример:")
                for line in example.split("\n"):
                    out.append(f"    {line}")
            out.append("")
    out.append(f"Всего команд: {total}.")
    return "\n".join(out)


def full_instruction() -> str:
    """Инструкция целиком: правила + каталог всех команд."""
    return (HEADER.format(version=__version__)
            + "\n" + SECTIONS
            + "\n\n" + commands_catalog()
            + "\n" + FOOTER)


def instruction_text(kind: str = "full") -> str:
    kind = (kind or "full").strip().lower()
    if kind in ("commands", "все", "каталог", "catalog"):
        return commands_catalog()
    return full_instruction()
