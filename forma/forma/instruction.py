"""Полная инструкция для нейросети: все команды в исполнимом виде.

Раньше помощнику доставался только «запрос» — сценарий, отчёт и замечания.
Справочник команд прикладывался один раз и кратко, поэтому модель регулярно
придумывала параметры, которых нет. Здесь два отдельных текста, которые
копируются кнопкой:

* `commands_catalog()` — **все команды** приложения, каждая в исполнимом виде:
  имя, синонимы, что делает, параметры с значениями по умолчанию и рабочий
  пример. Это то, что нужно модели, чтобы писать сценарий без выдумок;
* `full_instruction()` — правила работы целиком: синтаксис, оси, цвета,
  материалы, проверки, анимация, экспорт и полный каталог команд.

Тексты собираются из реестра `OPS`, поэтому новая команда попадает в
инструкцию автоматически, без правки документации вручную.
"""

