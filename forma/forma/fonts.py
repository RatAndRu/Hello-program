def _segment_shape(a, b, width: float) -> list[mf.CrossSection]:
    ax, ay = a
    bx, by = b
    dx, dy = bx - ax, by - ay
    length = math.hypot(dx, dy)
    if length < 1e-9:
        return []
    nx, ny = -dy / length * width / 2.0, dx / length * width / 2.0
    quad = mf.CrossSection([[(ax + nx, ay + ny), (bx + nx, by + ny),
                             (bx - nx, by - ny), (ax - nx, ay - ny)]]) if hasattr(
        mf.CrossSection, "__init__") else None
    if quad is None:
        return []
    return [quad]


def _circle_at(x: float, y: float, radius: float) -> mf.CrossSection:
    return mf.CrossSection.circle(radius, 16).translate([x, y])


def _polygon_shape(points: list[tuple[float, float]]) -> mf.CrossSection:
    # CrossSection из полигона: используем квадрат как основу и булеву замену нельзя,
    # поэтому строим многоугольник через convex/простой конструктор.
    return mf.CrossSection([points])


def text_cross_section(text: str, size: float = 20.0, weight: float | None = None,
                       align: str = "center", spacing: float = 1.1) -> tuple[mf.CrossSection, float]:
    """2D-контуры надписи. Высота заглавных = size, начало координат — базовая линия."""
    text = (text or "").strip()
    if not text:
        raise ValueError("Пустая надпись.")
    scale = float(size) / 6.0
    w_mm = float(weight) if weight else max(0.6, float(size) * 0.095)
    half = max(0.16, min(0.6, w_mm / scale / 2.0))
    advance = 4.0 + spacing
    shapes: list[mf.CrossSection] = []
    pen = 0.0
    for char in text:
        strokes = glyph_strokes(char)
        for line in strokes:
            pts = [(pen + x, y) for (x, y) in line]
            for a, b in zip(pts, pts[1:]):
                ax, ay = a
                bx, by = b
                dx, dy = bx - ax, by - ay
                length = math.hypot(dx, dy)
                if length < 1e-9:
                    continue
                nx, ny = -dy / length * half, dx / length * half
                # обход против часовой стрелки: иначе Clipper считает прямоугольник
                # отверстием и «съедает» штрих
                shapes.append(mf.CrossSection([[(ax - nx, ay - ny), (bx - nx, by - ny),
                                                (bx + nx, by + ny), (ax + nx, ay + ny)]]))
            for (x, y) in pts:
                shapes.append(mf.CrossSection.circle(half, 16).translate([x, y]))
        pen += advance
    if not shapes:
        raise ValueError("В надписи нет линий — проверьте символы.")
    cs = mf.CrossSection.batch_boolean(shapes, mf.OpType.Add)
    total = (pen - spacing) * scale
    shift = 0.0
    if align == "center":
        shift = -total / 2.0
    elif align == "right":
        shift = -total
    cs = cs.scale([scale, scale]).translate([shift, 0.0])
    return cs, total


def text_solid(text: str, size: float = 20.0, depth: float = 2.0,
               weight: float | None = None, align: str = "center",
               spacing: float = 1.1) -> tuple[mf.Manifold, float]:
    """Готовая объёмная надпись: стоит на Z=0, выдавлена вверх на depth."""
    cs, width = text_cross_section(text, size=size, weight=weight, align=align,
                                   spacing=spacing)
    depth = max(0.2, float(depth))
    solid = cs.extrude(depth)
    if solid.is_empty() or solid.volume() <= 1e-9:
        raise ValueError("Надпись получилась пустой.")
    return solid, width
