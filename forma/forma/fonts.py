def _arc(cx: float, cy: float, rx: float, ry: float, a0: float, a1: float,
         n: int = 20) -> list[tuple[float, float]]:
    return [(cx + rx * math.cos(math.radians(a0 + (a1 - a0) * i / n)),
             cy + ry * math.sin(math.radians(a0 + (a1 - a0) * i / n)))
            for i in range(n + 1)]


def _ring(cx: float, cy: float, rx: float, ry: float, n: int = 28) -> list[tuple[float, float]]:
    return _arc(cx, cy, rx, ry, 0.0, 360.0, n)


