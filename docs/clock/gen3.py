def gear_poly(z, c, ph, m=M):
    pr = m*z/2.0
    rt, rr = pr + m, max(0.2, pr - 1.25*m)
    step = 2*math.pi/z
    pts = []
    for i in range(z):
        a0 = i*step + math.radians(ph)
        for rad, da in ((rr, -0.30*step), (rt, -0.16*step), (rt, 0.16*step), (rr, 0.30*step)):
            pts.append((c[0] + rad*cos(a0+da), c[1] + rad*sin(a0+da)))
    return pts

def _dps(p, a, b):
    ax, ay = b[0]-a[0], b[1]-a[1]
    L = ax*ax + ay*ay
    if L < 1e-12:
        return hypot(p[0]-a[0], p[1]-a[1])
    t = max(0.0, min(1.0, ((p[0]-a[0])*ax + (p[1]-a[1])*ay)/L))
    return hypot(p[0]-(a[0]+t*ax), p[1]-(a[1]+t*ay))

def poly_gap(A, Bp, cut=10.0):
    best = 1e9
    n = len(A)
    for i in range(n):
        a1, a2 = A[i], A[(i+1) % n]
        ax, az = (a1[0]+a2[0])/2, (a1[1]+a2[1])/2
        for j in range(len(Bp)):
            b1, b2 = Bp[j], Bp[(j+1) % len(Bp)]
            if hypot(ax-(b1[0]+b2[0])/2, az-(b1[1]+b2[1])/2) > cut:
                continue
            d = min(_dps(a1, b1, b2), _dps(a2, b1, b2), _dps(b1, a1, a2), _dps(b2, a1, a2))
            if d < best:
                best = d
                if best < 1e-6:
                    return 0.0
    return best

