def circ(c1, r1, c2, r2, prefer):
    dx, dz = c2[0]-c1[0], c2[1]-c1[1]
    d = hypot(dx, dz)
    a = (r1*r1 - r2*r2 + d*d)/(2*d)
    h = math.sqrt(max(0.0, r1*r1 - a*a))
    ux, uz = dx/d, dz/d
    bx, bz = c1[0] + a*ux, c1[1] + a*uz
    p1 = (bx - h*uz, bz + h*ux)
    p2 = (bx + h*uz, bz - h*ux)
    return p1 if hypot(p1[0]-prefer[0], p1[1]-prefer[1]) < hypot(p2[0]-prefer[0], p2[1]-prefer[1]) else p2

