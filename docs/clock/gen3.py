def ring(nm, r_out, r_in, y_back, y_front, c, seg=144):
    cylv(nm+"_a", r_out, y_back, y_front, c[0], c[1], seg)
    cylv(nm+"_b", r_in, y_back-0.2, y_front+0.2, c[0], c[1], seg)
    w(f"{nm} = difference [{nm}_a, {nm}_b]")

def bar(nm, p1, p2, wide, y_back, y_front, rnd=2.0, ext=0.0, ymat=None):
    L = hypot(p2[0]-p1[0], p2[1]-p1[1]) + 2*ext
    th = degrees(math.atan2(p2[1]-p1[1], p2[0]-p1[0]))
    mx, mz = (p1[0]+p2[0])/2, (p1[1]+p2[1])/2
    thin = abs(y_back - y_front)
    rnd = min(rnd, thin*0.45, wide*0.45)
    w(f"{nm} = box size=[{n(L)}, {n(thin)}, {n(wide)}] round={n(rnd)} center=да")
    w(f"{nm} = rotate [{nm}] angle={n(-th)} axis=y")
    w(f"{nm} = translate [{nm}] offset=[{n(mx)}, {n((y_back+y_front)/2)}, {n(mz)}]")

def gear(nm, z, ph, c, y, bore=0.0, hub=0.0, hub_h=0.0, m=M):
    th = y[0]-y[1]
    w(f"{nm} = gear teeth={z} module={n(m,3)} thickness={n(th)} bore={n(bore)}"
      + (f" hub={n(hub,1)} hub_height={n(hub_h,1)}" if hub else ""))
    w(f"{nm} = rotate [{nm}] angle=90 axis=x")
    w(f"{nm} = rotate [{nm}] angle={n(-ph,3)} axis=y")
    w(f"{nm} = translate [{nm}] offset=[{n(c[0])}, {n(y[0])}, {n(c[1])}]")

def screw(nm, c, ytop, ln, d=4.0):
    cylv(nm+"_гa", d*1.02, ytop+1.6, ytop-0.1, c[0], c[1], 36)
    cylv(nm+"_гb", d*0.40, ytop+1.7, ytop-0.6, c[0], c[1], 20)
    cylv(nm+"_ш", d*0.5, ytop+0.1, ytop-abs(ln), c[0], c[1], 24)
    w(f"{nm} = union [{nm}_гa, {nm}_ш]")
    w(f"{nm} = difference [{nm}, {nm}_гb]")

def arbor(nm, c, y_back, y_front, r=2.4):
    cylv(nm, r, y_back, y_front, c[0], c[1], 24)

